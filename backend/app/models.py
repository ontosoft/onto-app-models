import uuid
from datetime import datetime, timezone

from pydantic import EmailStr
from typing import Any, Dict, Literal
from sqlalchemy import DateTime, Column, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlmodel import Field,  SQLModel, Relationship


def get_datetime_utc() -> datetime:
    return datetime.now(timezone.utc)

# Shared properties
class UserBase(SQLModel):
    email: EmailStr = Field(unique=True, index=True, max_length=255)
    is_active: bool = True
    is_superuser: bool = False
    full_name: str | None = Field(default=None, max_length=255)


# Properties to receive via API on creation
class UserCreate(UserBase):
    password: str = Field(min_length=8, max_length=128)


class UserRegister(SQLModel):
    email: EmailStr = Field(max_length=255)
    password: str = Field(min_length=8, max_length=128)
    full_name: str | None = Field(default=None, max_length=255)


# Properties to receive via API on update, all are optional
class UserUpdate(UserBase):
    email: EmailStr | None = Field(default=None, max_length=255)  # type: ignore
    password: str | None = Field(default=None, min_length=8, max_length=128)


class UserUpdateMe(SQLModel):
    full_name: str | None = Field(default=None, max_length=255)
    email: EmailStr | None = Field(default=None, max_length=255)


class UpdatePassword(SQLModel):
    current_password: str = Field(min_length=8, max_length=128)
    new_password: str = Field(min_length=8, max_length=128)


# Database model, database table inferred from class name
class User(UserBase, table=True):
    id: uuid.UUID = Field(default_factory=uuid.uuid4, primary_key=True)
    hashed_password: str
    created_at: datetime | None = Field(
        default_factory=get_datetime_utc,
        sa_type=DateTime(timezone=True),  # type: ignore
    )
    appmodels: list["AppModel"] = Relationship(back_populates="owner")  

# Properties to return via API, id is always required
class UserPublic(UserBase):
    id: uuid.UUID


class UsersPublic(SQLModel):
    data: list[UserPublic]
    count: int

class AppModelBase(SQLModel):
    title: str = Field(min_length=1, max_length=255)
    description: str | None = Field(default=None, max_length=1024)
    knowledge_graph_rdf: str


# Properties to receive via API on creation
class AppModelCreate(AppModelBase):
    pass

# Properties to receive via API on update, all are optional
class AppModelUpdate(SQLModel):
    title: str | None = Field(default=None, min_length=1, max_length=255)
    description: str | None = Field(default=None, max_length=1024)
    knowledge_graph_rdf: str = Field(min_length=2)  # type: ignore
    # Only superusers may change this (enforced in the route).
    is_public: bool | None = None

class AppModel(AppModelBase, table=True):
    id: uuid.UUID = Field(default_factory=uuid.uuid4, primary_key=True)
    owner_id: uuid.UUID = Field(foreign_key="user.id", nullable=False)
    # Public models are visible (read/run) to every authenticated user;
    # editing and deleting stay owner/superuser-only.
    is_public: bool = Field(default=False, nullable=False)
    # Provenance: set when this FAM was generated from a ShapesDocument.
    # Several AppModels may point at the same document (candidate models).
    shapes_id: uuid.UUID | None = Field(
        default=None, foreign_key="shapesdocument.id", nullable=True
    )
    # How the model came to be: 
    #   - None = written by hand, 
    #   - "rule-based" = deterministic SHACL converter, 
    #   - "llm:<model-id>" = generated by an LLM.
    generation_method: str | None = Field(default=None, max_length=64)
    owner: User = Relationship(back_populates="appmodels")  # type: ignore
    created_at: datetime | None = Field(
        default_factory=get_datetime_utc,
        sa_type=DateTime(timezone=True),  # type: ignore
    )
    # To avoid constant converting from JSON to RDF format both versions 
    # are stored in the table. The user enters and  edits s the RDF graph
    # while the system converts it to JSON-LD in order to make advanced search possible
    knowledge_graph_json : Any = Field(default={}, sa_column=Column(JSONB))
    knowledge_graph_rdf: str = Field(default=None, sa_column=Column(Text))

# Properties to return via API
class AppModelPublic(AppModelBase):
    id: uuid.UUID
    owner_id: uuid.UUID
    created_at: datetime | None = None
    knowledge_graph_rdf: str | None = None
    is_public: bool = False
    shapes_id: uuid.UUID | None = None
    generation_method: str | None = None

class AppModelsPublic(SQLModel):
    data: list[AppModelPublic]
    count: int


class ShapesDocumentBase(SQLModel):
    name: str = Field(min_length=1, max_length=255)
    # Shapes language of `content`. Only formats with a registered FAM
    # converter are accepted on upload ("shacl" for now; "shex" planned).
    format: str = Field(max_length=32)
    content: str


# Properties to receive via API on upload
class ShapesDocumentCreate(ShapesDocumentBase):
    format: Literal["shacl"] = "shacl"
    content: str = Field(min_length=1)


class ShapesDocument(ShapesDocumentBase, table=True):
    id: uuid.UUID = Field(default_factory=uuid.uuid4, primary_key=True)
    owner_id: uuid.UUID = Field(foreign_key="user.id", nullable=False)
    # Public shapes are visible to every authenticated user, who may also
    # generate their own FAM candidates from them; deleting and changing
    # visibility stay owner/superuser-only.
    is_public: bool = Field(default=False, nullable=False)
    # sha256 over content: identical uploads BY THE SAME USER reuse the same
    # row, so that user's FAM candidates group together. Different users may
    # each keep their own copy of the same shapes (unique per owner_id +
    # content_hash, see the migration).
    content_hash: str = Field(index=True, max_length=64)
    content: str = Field(default=None, sa_column=Column(Text))
    created_at: datetime | None = Field(
        default_factory=get_datetime_utc,
        sa_type=DateTime(timezone=True),  # type: ignore
    )


# Properties to receive via API on update (visibility only for now;
# content stays immutable because candidates were generated from it)
class ShapesDocumentUpdate(SQLModel):
    # Only superusers may change this (enforced in the route).
    is_public: bool | None = None


# Properties to return via API
class ShapesDocumentPublic(ShapesDocumentBase):
    id: uuid.UUID
    owner_id: uuid.UUID
    created_at: datetime | None = None
    is_public: bool = False


class ShapesDocumentsPublic(SQLModel):
    data: list[ShapesDocumentPublic]
    count: int


# Generic message
class Message(SQLModel):
    message: str


# JSON payload containing access token
class Token(SQLModel):
    access_token: str
    token_type: str = "bearer"


# Contents of JWT token
class TokenPayload(SQLModel):
    sub: str | None = None


class NewPassword(SQLModel):
    token: str
    new_password: str = Field(min_length=8, max_length=128)
