"""Tests for the protocol-level agentic model tester (app/model_tester).

The LLM is replaced by deterministic deciders, so CI needs no Ollama — but
everything else is real: the model is generated by the rule-based generator,
the environment drives the real AppEngine/ProcessEngine (including per-form
SHACL validation), and the oracles run the real pySHACL and Pellet checks.

The deciders parse the environment's stable observation markers (``FIELDS:``,
``BUTTONS:``, ``APPLICATION FINISHED:``) from the step prompt — the same text
an LLM sees — so the tests also pin the observation format the prompts and
stage 2 rely on.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from rdflib import RDF, Graph, Namespace

from app.model_generator import generate_appmodel_from_shacl
from app.model_tester import AgentAction, TraceStep, run_model_test
from app.model_tester.reasoning import check_trace_consistency
from app.model_tester.violations import DeterministicDecider

OBOP = Namespace("http://purl.org/net/obop/")

EXAMPLES = Path(__file__).parent.parent / "model_generator" / "examples"

#: Shapes with a violable constraint (minLength) for the adversarial test —
#: the stock string_form example has nothing an adversarial value could break.
MIN_LENGTH_SHAPES = """\
@prefix sh:  <http://www.w3.org/ns/shacl#> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix v1:  <http://purl.org/goodrelations/v1#> .

<http://example.org/generated/agent-test/BusinessEntityShape>
    a sh:NodeShape ;
    sh:targetClass v1:BusinessEntity ;
    sh:property [
        sh:path      v1:legalName ;
        sh:datatype  xsd:string ;
        sh:name      "Legal name" ;
        sh:minLength 5 ;
        sh:minCount  1 ;
    ] .
"""


# --------------------------------------------------------------------- helpers


def _first_empty_field(prompt: str) -> str | None:
    """Name of the first empty field on the current page, if any."""
    match = re.search(r'^  - "([^"]+)" \([^)]*\) = <empty>$', prompt, re.MULTILINE)
    return match.group(1) if match else None


def _first_button(prompt: str) -> str | None:
    """Label of the first button on the current page, if any."""
    match = re.search(r'^  - "([^"]+)" \[[a-z_]+\]$', prompt, re.MULTILINE)
    return match.group(1) if match else None


def _empty_fields(prompt: str) -> list[str]:
    """Names of ALL empty fields on the current page (for fill_form)."""
    return re.findall(r'^  - "([^"]+)" \([^)]*\) = <empty>$', prompt, re.MULTILINE)


def _submit_button(prompt: str) -> str | None:
    """Label of the submit button on the current page, if any."""
    match = re.search(r'^  - "([^"]+)" \[submit\]$', prompt, re.MULTILINE)
    return match.group(1) if match else None


def _cooperative_decider(values: dict[str, str]):
    """A rule-based stand-in for the LLM: fill empty fields with the given
    values, click the first button otherwise, finish once the app reports it
    is done. This is exactly the policy the cooperative prompt asks for."""

    def decide(system: str, prompt: str) -> tuple[AgentAction, int]:
        if "APPLICATION FINISHED: yes" in prompt:
            return AgentAction(action="finish", verdict="pass", reason="completed"), 0
        field = _first_empty_field(prompt)
        if field is not None:
            return (
                AgentAction(
                    action="fill", field=field, value=values.get(field, "Test value")
                ),
                0,
            )
        button = _first_button(prompt)
        if button is not None:
            return AgentAction(action="click", button=button), 0
        return AgentAction(action="finish", verdict="fail", reason="nothing to do"), 0

    return decide


class _AdversarialDecider:
    """Scripted adversarial user: submit an invalid value first, expect the
    rejection, then correct it and complete the run (the adversarial prompt's
    policy). State advances only on form pages; message pages are clicked
    through."""

    def __init__(self, field: str, bad: str, good: str) -> None:
        self.field = field
        self.bad = bad
        self.good = good
        self.phase = 0  # 0 fill bad, 1 submit, 2 fill good, 3 submit, 4 done

    def __call__(self, system: str, prompt: str) -> tuple[AgentAction, int]:
        if "APPLICATION FINISHED: yes" in prompt:
            return (
                AgentAction(
                    action="finish", verdict="pass", reason="rejected, then completed"
                ),
                0,
            )
        if "FIELDS:" in prompt:
            if self.phase == 0:
                self.phase = 1
                return AgentAction(action="fill", field=self.field, value=self.bad), 0
            if self.phase == 1:
                self.phase = 2
                return AgentAction(
                    action="click", button=_first_button(prompt) or ""
                ), 0
            if self.phase == 2:
                # We are here again => the bad submit was rejected. Correct it.
                self.phase = 3
                return AgentAction(action="fill", field=self.field, value=self.good), 0
            if self.phase == 3:
                self.phase = 4
                return AgentAction(
                    action="click", button=_first_button(prompt) or ""
                ), 0
            # A form after the corrected submit means the good value was also
            # rejected — give up with a meaningful verdict.
            return (
                AgentAction(
                    action="finish", verdict="fail", reason="valid data was rejected"
                ),
                0,
            )
        # Notification / message pages: click through.
        button = _first_button(prompt)
        if button is not None:
            return AgentAction(action="click", button=button), 0
        return AgentAction(action="finish", verdict="fail", reason="nothing to do"), 0


# ----------------------------------------------------------------------- tests


def test_cooperative_run_confirms_string_form_model() -> None:
    """Green light end to end: generated model + cooperative agent must pass
    all oracles (FAM well-formedness, completion, SHACL round-trip, DL trace
    consistency)."""
    shapes_ttl = (EXAMPLES / "string_form.shapes.ttl").read_text(encoding="utf-8")
    generated = generate_appmodel_from_shacl(shapes_ttl)

    report = run_model_test(
        generated.rdf,
        shapes_ttl,
        "cooperative",
        _cooperative_decider({"Field 1": "Acme GmbH"}),
    )

    oracle_names = {oracle.name: oracle for oracle in report.oracles}
    assert oracle_names["fam_well_formed"].passed, oracle_names[
        "fam_well_formed"
    ].detail
    assert oracle_names["process_completed"].passed, oracle_names[
        "process_completed"
    ].detail
    assert oracle_names["shacl_round_trip"].passed, oracle_names[
        "shacl_round_trip"
    ].detail
    assert oracle_names["dl_trace_consistency"].passed, oracle_names[
        "dl_trace_consistency"
    ].detail
    assert report.completed
    assert report.transcript is not None and report.transcript.verdict == "pass"
    assert report.passed, "the model should be confirmed"


def test_adversarial_run_requires_a_rejection() -> None:
    """The engine must reject a value violating sh:minLength (same form again),
    and the corrected run must still complete — the adversarial green light."""
    generated = generate_appmodel_from_shacl(MIN_LENGTH_SHAPES)

    report = run_model_test(
        generated.rdf,
        MIN_LENGTH_SHAPES,
        "adversarial",
        _AdversarialDecider(field="Legal name", bad="ab", good="Acme GmbH"),
    )

    oracle_names = {oracle.name: oracle for oracle in report.oracles}
    assert report.validation_rejections >= 1, "the invalid submit was not rejected"
    assert oracle_names["invalid_data_rejected"].passed
    assert oracle_names["process_completed"].passed, oracle_names[
        "process_completed"
    ].detail
    assert report.passed, "the adversarial run should pass (rejected, then completed)"


def test_cooperative_fill_form_confirms_in_fewer_steps() -> None:
    """The batched fill_form action (all values + submit in ONE decision)
    must reach the same green light as the field-by-field run — it exists to
    cut LLM calls roughly by the number of fields per form."""
    shapes_ttl = (EXAMPLES / "string_form.shapes.ttl").read_text(encoding="utf-8")
    generated = generate_appmodel_from_shacl(shapes_ttl)

    def decide(system: str, prompt: str) -> tuple[AgentAction, int]:
        if "APPLICATION FINISHED: yes" in prompt:
            return AgentAction(action="finish", verdict="pass", reason="completed"), 0
        empty = _empty_fields(prompt)
        submit = _submit_button(prompt)
        if empty and submit:
            return (
                AgentAction(
                    action="fill_form",
                    fields={name: "Acme GmbH" for name in empty},
                    button=submit,
                ),
                0,
            )
        button = _first_button(prompt)
        if button is not None:
            return AgentAction(action="click", button=button), 0
        return AgentAction(action="finish", verdict="fail", reason="nothing to do"), 0

    report = run_model_test(generated.rdf, shapes_ttl, "cooperative", decide)

    assert report.passed, "the model should be confirmed via fill_form"
    assert report.transcript is not None
    actions = [step.action.action for step in report.transcript.steps]
    assert "fill_form" in actions
    # One decision per page: form, confirmation(s), final OK, finish — the
    # per-field fill actions must not appear at all.
    assert "fill" not in actions
    assert len(actions) <= 5, f"expected few steps, got: {actions}"


def test_deterministic_adversary_minlength() -> None:
    """The shapes-derived decider must find the minLength violation on its
    own (no scripted field name), get rejected, correct, and pass."""
    generated = generate_appmodel_from_shacl(MIN_LENGTH_SHAPES)

    report = run_model_test(
        generated.rdf,
        MIN_LENGTH_SHAPES,
        "adversarial",
        DeterministicDecider(MIN_LENGTH_SHAPES, adversarial=True),
    )

    assert report.validation_rejections >= 1
    assert report.completed
    assert report.passed, [o.detail for o in report.oracles if not o.passed]


def test_deterministic_adversary_restaurant() -> None:
    """Multi-form app: the first violable constraint is menuName's
    sh:minCount on the SECOND form — the decider must pass the
    unconstrained restaurant form validly, omit the menu name, see the
    rejection, correct it and run the remaining subprocesses (dish with a
    valid xsd:decimal price, ingredient) to the end. DL oracle skipped to
    keep the suite fast; the other oracles run."""
    shapes_ttl = (EXAMPLES / "restaurant.shapes.ttl").read_text(encoding="utf-8")
    generated = generate_appmodel_from_shacl(shapes_ttl)

    report = run_model_test(
        generated.rdf,
        shapes_ttl,
        "adversarial",
        DeterministicDecider(shapes_ttl, adversarial=True),
        dl_oracle=False,
    )

    assert report.validation_rejections >= 1
    assert report.completed
    assert report.passed, [o.detail for o in report.oracles if not o.passed]


def test_dl_trace_oracle_detects_category_confusion() -> None:
    """The DL oracle must turn red when the trace claims an engine decision
    was observed at a node the model declares to be an Action — this is the
    disjointness axiom (EngineDecision owl:disjointWith Action) biting."""
    shapes_ttl = (EXAMPLES / "string_form.shapes.ttl").read_text(encoding="utf-8")
    generated = generate_appmodel_from_shacl(shapes_ttl)

    graph = Graph()
    graph.parse(data=generated.rdf, format="turtle")
    action_node = next(graph.subjects(RDF.type, OBOP.SubmitBlockAction), None)
    if action_node is None:
        pytest.skip("generated model has no SubmitBlockAction individual")

    bogus_trace = [TraceStep("decision_observed", str(action_node))]
    consistent, detail = check_trace_consistency(generated.rdf, bogus_trace)
    assert not consistent, (
        "Pellet should report an inconsistency for an Action observed as an "
        f"EngineDecision, but said: {detail}"
    )


def test_obop_axioms_reject_category_confusion_in_the_model() -> None:
    """The OBOP V 0.2 TBox must make a mis-assembled MODEL inconsistent even
    with an empty trace: a node typed as both Field and Button violates the
    visual-element disjointness, and a button sitting in two layouts violates
    the functional belongsToVisual together with the generator's
    owl:AllDifferent (without which the reasoner would just merge the two
    layouts)."""
    shapes_ttl = (EXAMPLES / "string_form.shapes.ttl").read_text(encoding="utf-8")
    generated = generate_appmodel_from_shacl(shapes_ttl)

    # A field that is also a button (disjointness axiom).
    graph = Graph()
    graph.parse(data=generated.rdf, format="turtle")
    field = next(graph.subjects(RDF.type, OBOP.Field))
    graph.add((field, RDF.type, OBOP.Button))
    consistent, detail = check_trace_consistency(graph.serialize(format="turtle"), [])
    assert not consistent, f"Field+Button typing should be inconsistent: {detail}"

    # A button placed in two distinct layouts (functionality + AllDifferent).
    graph = Graph()
    graph.parse(data=generated.rdf, format="turtle")
    button = next(graph.subjects(RDF.type, OBOP.Button))
    second_layout = next(
        layout
        for layout in graph.subjects(RDF.type, OBOP.VerticalLayout)
        if (button, OBOP.belongsToVisual, layout) not in graph
    )
    graph.add((button, OBOP.belongsToVisual, second_layout))
    consistent, detail = check_trace_consistency(graph.serialize(format="turtle"), [])
    assert not consistent, (
        f"two layouts for one button should be inconsistent: {detail}"
    )
